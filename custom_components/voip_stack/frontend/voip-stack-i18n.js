const DYNAMIC_MESSAGES = [
  [/^Calling (.+)\.\.\.$/, "Calling {name}..."],
  [/^In Call: (.+)$/, "In Call: {name}"],
  [/^Call with (.+) ended\.$/, "Call with {name} ended."],
  [/^Incoming: (.+)$/, "Incoming: {name}"],
  [/^Answering (.+)\.\.\.$/, "Answering {name}..."],
  [/^(.+) is ringing\.\.\.$/, "{name} is ringing..."],
  [/^Missing phone: (.+)$/, "Missing phone: {name}"],
];

export function voipStackLanguage(hass) {
  return String(hass?.language || hass?.locale?.language || "en").toLowerCase();
}

export function voipStackTranslate(hass, text) {
  const value = String(text ?? "");
  const language = voipStackLanguage(hass);
  const dictionary = language === "it" || language.startsWith("it-")
    ? IT
    : language === "de" || language.startsWith("de-")
    ? DE
    : language === "pt" || language.startsWith("pt-")
      ? PT_BR
      : language === "cs" || language.startsWith("cs-")
        ? CS
        : null;
  if (!dictionary) return value;
  if (dictionary[value]) return dictionary[value];
  const reason = value.match(/^Reason: (.+)$/);
  if (reason) {
    return `${voipStackTranslate(hass, "Reason:")} ${voipStackTranslate(hass, reason[1])}`;
  }
  const videoReason = value.match(/^Video unavailable: (.+)$/);
  if (videoReason) {
    return `${voipStackTranslate(hass, "Video unavailable:")} ${voipStackTranslate(hass, videoReason[1])}`;
  }
  for (const [pattern, message] of DYNAMIC_MESSAGES) {
    const match = value.match(pattern);
    // Names remain literal data, including replacement tokens and SIP text.
    if (match && dictionary[message]) return dictionary[message].replace("{name}", () => match[1]);
  }
  return value;
}
