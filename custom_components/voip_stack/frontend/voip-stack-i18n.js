export function voipStackLanguage(hass) {
  return String(hass?.language || hass?.locale?.language || "en").toLowerCase();
}

export function voipStackTranslate(hass, text) {
  const value = String(text ?? "");
  const language = voipStackLanguage(hass);
  const dictionary = language === "de" || language.startsWith("de-")
    ? DE
    : language === "pt" || language === "pt-br"
      ? PT_BR
      : null;
  if (!dictionary) return value;
  if (dictionary[value]) return dictionary[value];
  const reason = value.match(/^Reason: (.+)$/);
  if (reason) {
    const label = language.startsWith("de") ? "Grund" : "Motivo";
    return `${label}: ${voipStackTranslate(hass, reason[1])}`;
  }
  const videoReason = value.match(/^Video unavailable: (.+)$/);
  if (videoReason) {
    const label = language.startsWith("de")
      ? "Video nicht verfügbar"
      : "Vídeo indisponível";
    return `${label}: ${voipStackTranslate(hass, videoReason[1])}`;
  }

  const replacements = language === "de" || language.startsWith("de-")
    ? [
      [/^Incoming: (.+)$/, "Eingehend: $1"],
      [/^Answering (.+)\.\.\.$/, "$1 wird angenommen..."],
      [/^In Call: (.+)$/, "Im Gespräch: $1"],
      [/^Calling (.+)\.\.\.$/, "$1 wird angerufen..."],
      [/^(.+) is ringing\.\.\.$/, "$1 klingelt..."],
      [/^Call (.+) ended\.$/, "Gespräch mit $1 beendet."],
      [/^Missing phone: (.+)$/, "Fehlendes Telefon: $1"],
    ]
    : [
      [/^Incoming: (.+)$/, "Recebendo: $1"],
      [/^Answering (.+)\.\.\.$/, "Atendendo $1..."],
      [/^In Call: (.+)$/, "Em chamada: $1"],
      [/^Calling (.+)\.\.\.$/, "Chamando $1..."],
      [/^(.+) is ringing\.\.\.$/, "$1 está tocando..."],
      [/^Call (.+) ended\.$/, "Chamada com $1 encerrada."],
      [/^Missing phone: (.+)$/, "Telefone ausente: $1"],
    ];
  for (const [pattern, replacement] of replacements) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  return value;
}
