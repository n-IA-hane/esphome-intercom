"""Declared HA clients from saved dashboards, popup opt-ins and migration data."""

from __future__ import annotations

import asyncio
from copy import deepcopy
import logging
import re

from homeassistant.components.lovelace.const import LOVELACE_DATA, ConfigNotFound
from homeassistant.core import callback
from homeassistant.const import EVENT_COMPONENT_LOADED
from homeassistant.exceptions import HomeAssistantError
from homeassistant.helpers.storage import Store

_LOGGER = logging.getLogger(__name__)
_CARD_TYPES = {"custom:voip-stack-card", "custom:voip-stack-dashboard-card"}
_BINDING_ID = re.compile(r"[A-Za-z0-9._~-]{16,128}")


def _configured_cards(value, path=""):
    """Read declarations even when their containing view/card is not rendered."""
    if isinstance(value, list):
        for index, item in enumerate(value):
            yield from _configured_cards(item, f"{path}/{index}")
    elif isinstance(value, dict):
        if value.get("type") in _CARD_TYPES:
            if (value["type"] == "custom:voip-stack-dashboard-card"
                    or value.get("mode", value.get("card_mode", "esp_mirror")) == "ha_softphone"):
                yield {"reference": path, "device_id": str(value.get("device_id") or value.get("entity_id") or ""),
                       "endpoint_id": str(value.get("endpoint_id") or "")}
        for key, item in value.items():
            if isinstance(item, (dict, list)):
                yield from _configured_cards(item, f"{path}/{key}")


class HaCardBindings:
    """One persistent configuration index, never browser presence or call state."""

    def __init__(self, hass, entry, runtime, on_change):
        self.hass, self.entry, self.runtime, self.on_change = hass, entry, runtime, on_change
        self._store = Store(hass, 1, f"voip_stack.ha_bindings.{entry.entry_id}", atomic_writes=True)
        self._dashboards, self._popups, self._index = {}, {}, {}
        self._lock = asyncio.Lock()
        self._unsubscribers = []
        self._task = None
        self._requested = False
        self._closed = False

    def _owned(self):
        return not self._closed and self.runtime.ha_bindings is self

    async def async_start(self):
        saved = await self._store.async_load()
        if not self._owned():
            return
        if isinstance(saved, dict):
            self._dashboards = {key: value for key, value in saved.get("dashboards", {}).items()
                                if isinstance(key, str) and isinstance(value, list)}
            self._popups = {key: value for key, value in saved.get("popups", {}).items()
                            if isinstance(key, str) and isinstance(value, dict)}
        self._reindex()
        self._unsubscribers.append(self.hass.bus.async_listen("lovelace_updated", self._schedule))
        self._unsubscribers.append(self.hass.bus.async_listen(EVENT_COMPONENT_LOADED, self._component_loaded))
        self._unsubscribers.append(self.runtime.endpoints.subscribe(lambda _event: self._reindex()))
        await self._async_reload(force=False)

    @callback
    def _component_loaded(self, event):
        if event.data.get("component") == "lovelace":
            self._schedule()

    @callback
    def _schedule(self, event=None):
        if not self._owned():
            return
        self._requested = True
        if self._task is None or self._task.done():
            self._task = self.hass.async_create_task(self._reload_requested(), "voip-ha-card-bindings")

    async def _reload_requested(self):
        while self._requested and self._owned():
            self._requested = False
            await self._async_reload(force=False)

    async def async_reload(self):
        """Explicit admin reload also refreshes cached YAML, without a watcher."""
        await self._async_reload(force=True)

    async def _async_reload(self, *, force):
        async with self._lock:
            if not self._owned():
                return
            data = self.hass.data.get(LOVELACE_DATA)
            dashboards = getattr(data, "dashboards", None)
            if isinstance(dashboards, dict):
                # During Lovelace bootstrap its typed dashboard map can still
                # be partial. Missing entries are authoritative only once loaded.
                current = {} if "lovelace" in self.hass.config.components else dict(self._dashboards)
                for url, export in tuple(dashboards.items()):
                    key = str(url or "default")
                    try:
                        try:
                            config = await export.async_load(force)
                        except ConfigNotFound:
                            # The autogenerated Overview has no saved card config.
                            # Recovery mode and genuine read errors retain the LKG.
                            if self.hass.config.recovery_mode or (await export.async_get_info()).get("mode") != "auto-gen":
                                raise
                            config = {}
                        if not isinstance(config, dict):
                            raise ValueError("invalid_dashboard_export")
                        current[key] = list(_configured_cards(config))
                    except (HomeAssistantError, OSError, ValueError, TypeError, RuntimeError):
                        # Failed/unavailable exports never assert an empty declaration.
                        if key in self._dashboards:
                            current[key] = self._dashboards[key]
                        _LOGGER.warning("VoIP dashboard association export unavailable: %s", key)
                        _LOGGER.debug("Dashboard association export failed: %s", key, exc_info=True)
                if not self._owned():
                    return
                if current != self._dashboards:
                    await self._save(current, self._popups)
                    self._dashboards = current
            self._reindex()

    async def _save(self, dashboards, popups):
        await self._store.async_save({"dashboards": dashboards, "popups": popups})

    def _resolve(self, selector):
        registry = self.runtime.endpoints
        endpoint = registry.by_device_id(selector.get("device_id")) if selector.get("device_id") else None
        if endpoint is None and selector.get("endpoint_id"):
            endpoint = registry.get(selector["endpoint_id"])
        if endpoint is None and not selector.get("device_id") and not selector.get("endpoint_id"):
            # Do not call the sole-HA-bound fallback here: that fallback queries
            # this owner, creating a cycle for an implicit card declaration.
            endpoint = registry.by_device_id(getattr(self.runtime, "preferred_phone_device_id", "")) or registry.get("default")
        return endpoint if endpoint is not None and str(endpoint.kind) in {"browser", "sip_account"} else None

    def _references(self):
        result = {}
        implicit = []
        def add(endpoint, row):
            if endpoint is not None:
                result.setdefault(endpoint.endpoint_id, []).append(row)
        for url, rows in self._dashboards.items():
            for row in rows:
                reference = {"source": "dashboard", "reference": f"dashboard:{url}{row['reference']}", "enabled": True}
                endpoint = self._resolve(row)
                if endpoint is None and not row.get("device_id") and not row.get("endpoint_id"):
                    implicit.append(reference)
                else:
                    add(endpoint, reference)
        for value in self._popups.values():
            add(self._resolve(value), {"source": "popup", "reference": f"popup:{value['user_id']}:{value['binding_id']}",
                "enabled": value.get("enabled") is True})
        for subentry in self.entry.subentries.values():
            data = subentry.data
            endpoint = self.runtime.endpoints.get(data.get("endpoint_id"))
            for row in data.get("ha_bindings", ()):
                if isinstance(row, dict) and row.get("source") == "migration" and isinstance(row.get("reference"), str):
                    add(endpoint, {"source": "migration", "reference": row["reference"], "enabled": row.get("enabled", True) is True})
        candidates = [identity for identity, rows in result.items() if any(row["enabled"] for row in rows)]
        if len(candidates) == 1:
            for row in implicit:
                add(self.runtime.endpoints.get(candidates[0]), row)
        return {identity: tuple(sorted(rows, key=lambda row: (row["source"], row["reference"])))
                for identity, rows in result.items()}

    def _reindex(self):
        if not self._owned():
            return
        current = self._references()
        changed = frozenset(identity for identity in current.keys() | self._index.keys()
                            if current.get(identity) != self._index.get(identity))
        self._index = current
        if changed:
            self.on_change(changed)

    def has_binding(self, endpoint_id):
        return any(row["enabled"] for row in self.references(endpoint_id))

    def references(self, endpoint_id):
        return tuple(dict(row) for row in self._references().get(str(endpoint_id), ())) if self._owned() else ()

    def popup_binding(self, user_id, binding_id):
        value = self._popups.get(f"{user_id}:{binding_id}")
        return deepcopy(value) if value is not None else None

    async def async_set_popup_binding(self, user_id, binding_id, endpoint_id, enabled):
        """Persist an explicitly authorized browser choice; WS owns authorization."""
        if (not isinstance(user_id, str) or not user_id or len(user_id) > 128
                or not isinstance(binding_id, str) or not _BINDING_ID.fullmatch(binding_id)
                or not isinstance(endpoint_id, str) or not isinstance(enabled, bool)):
            raise ValueError("invalid_popup_binding")
        async with self._lock:
            if not self._owned():
                raise ValueError("ha_bindings_unavailable")
            previous = self.popup_binding(user_id, binding_id)
            if enabled and self._resolve({"endpoint_id": endpoint_id}) is None:
                raise ValueError("unknown_ha_account")
            value = {"user_id": user_id, "binding_id": binding_id,
                     "endpoint_id": endpoint_id or (previous or {}).get("endpoint_id", ""), "enabled": enabled}
            if value != previous:
                popups = {**self._popups, f"{user_id}:{binding_id}": value}
                await self._save(self._dashboards, popups)
                if not self._owned():
                    raise ValueError("ha_bindings_unavailable")
                self._popups = popups
                self._reindex()
            return deepcopy(value)

    async def async_close(self):
        self._closed = True
        for unsubscribe in self._unsubscribers:
            unsubscribe()
        self._unsubscribers.clear()
        if self._task is not None and not self._task.done():
            self._task.cancel()
            await asyncio.gather(self._task, return_exceptions=True)
